  const LANGS = ['en', 'ar', 'tr'];
  let lang = 'en';
  const rules = {};

  const fill = (text, vars) => (vars ? text.replace(/\{(\w+)\}/g, (m, k) => (vars[k] != null ? String(vars[k]) : m)) : text);

  function t(text, vars) {
    const dictionary = lang === 'tr' ? TR : lang === 'ar' ? AR : {};
    return fill(dictionary[text] != null ? dictionary[text] : text, vars);
  }

  // A counted word, such as plural('card', 3): "3 cards", or "3 بطاقات".
  function plural(word, n, vars) {
    const turkish = { card: 'kart', player: 'oyuncu', set: 'set', slot: 'yuva', 'empty slot': 'boş yuva', token: 'token' };
    if (lang === 'tr') return `${n} ${turkish[word] || word}`;
    const forms = PLURALS[word][lang] || PLURALS[word].en;
    if (!rules[lang]) rules[lang] = new Intl.PluralRules(lang);
    const form = forms[rules[lang].select(n)] || forms.other;
    return fill(form, { ...vars, n });
  }

  // The translated text split around its {name} marks, with the values in place: for text that
  // holds elements, such as "{n} rating" with the number in bold.
  function parts(text, vars) {
    return t(text).split(/(\{\w+\})/).filter(Boolean).flatMap((piece) => {
      const m = /^\{(\w+)\}$/.exec(piece);
      return m && vars[m[1]] !== undefined ? [].concat(vars[m[1]]) : [piece];
    }).filter((piece) => piece != null && piece !== '');
  }

  const api = {
    AR, TR, PLURALS, LANGS, t, plural, parts,
    setLang(next) { lang = LANGS.includes(next) ? next : 'en'; return lang; },
    lang: () => lang,
    dir: () => (lang === 'ar' ? 'rtl' : 'ltr'),
    // For dates and times; Arabic keeps the digits the Web App uses (0-9).
    locale: () => (lang === 'ar' ? 'ar-u-nu-latn' : lang === 'tr' ? 'tr-TR' : 'en-GB'),
  };
  if (typeof module === 'object' && module.exports) module.exports = api;
  else (root.FutFox = root.FutFox || {}).i18n = api;
